// tests/copy-lint.test.ts — Unit tests for Copy-Lint rules and vectors (Part 5.9)
import { describe, it, expect } from 'vitest';
import { lintTextEntry } from '../lib/copy-lint';

describe('Copy-Lint Vectors (Part 5.9)', () => {
  it('fails "SOC 2 certified" and "compliant with GDPR" without an evidence link', () => {
    const f1 = lintTextEntry({
      path: 'test.soc2',
      text: 'Our infrastructure is SOC 2 certified.',
    });
    expect(f1.length).toBeGreaterThan(0);
    expect(f1[0].rule).toBe('unverified-claim');

    const f2 = lintTextEntry({
      path: 'test.gdpr',
      text: 'We are fully compliant with GDPR.',
    });
    expect(f2.length).toBeGreaterThan(0);
    expect(f2[0].rule).toBe('unverified-claim');
  });

  it('passes "SOC 2 certified" and "compliant with GDPR" when an evidenceUrl is provided', () => {
    const f1 = lintTextEntry({
      path: 'test.soc2',
      text: 'Our infrastructure is SOC 2 certified.',
      evidenceUrl: 'https://example.com/security/soc2-report',
    });
    expect(f1).toEqual([]);

    const f2 = lintTextEntry({
      path: 'test.gdpr',
      text: 'We are compliant with GDPR.',
      evidenceUrl: 'https://example.com/privacy/dpa',
    });
    expect(f2).toEqual([]);
  });

  it('passes the standing AI disclosure line "Outputs are generated by AI and may contain errors"', () => {
    const res = lintTextEntry({
      path: 'site.standingAiDisclosure',
      text: 'Outputs are generated by AI and may contain errors. Check anything important.',
    });
    expect(res).toEqual([]);
  });

  it('fails "unlock your workflow" under the banned hype rule even if an evidenceUrl exists', () => {
    const res = lintTextEntry({
      path: 'hero.headline',
      text: 'Unlock your workflow with AI.',
      evidenceUrl: 'https://example.com/proof',
    });
    expect(res.length).toBe(1);
    expect(res[0].rule).toBe('banned-hype');
    expect(res[0].matchedPhrase.toLowerCase()).toContain('unlock');
  });
});

